#!/usr/bin/env python3
"""Data integrity + provenance audit. Run from the repo root:
    python3 scripts/audit.py
Fails (non-zero exit) if the SERVED curriculum contains anything unverified,
any item is missing required fields or provenance, ids collide, a can_do goal
points at an unknown id, or a quarantined id leaks back into a pack.
Regenerates VERIFICATION_LOG.md. The served curriculum is verified-only by
construction — there is no draft mode."""
import json
import os
import sys

try:
    sys.stdout.reconfigure(encoding='utf-8')  # console may default to cp932 on Windows
except Exception:
    pass

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'data')
REQUIRED = ('id', 'jp', 'kana', 'en', 'tier', 'status', 'sources')
errors = []
log = []
ids = set()
counts = {'verified': 0, 'other': 0}

ix = json.load(open(os.path.join(DATA, 'index.json'), encoding='utf-8'))

for f in ix['packs']:
    pack = json.load(open(os.path.join(DATA, f), encoding='utf-8'))
    for raw in pack['items']:
        it = dict(raw)
        it.setdefault('domain', pack.get('domain'))
        it.setdefault('status', pack.get('status'))
        it.setdefault('sources', pack.get('sources'))
        iid = it.get('id', '<no-id>')
        # required fields
        for k in REQUIRED:
            if not it.get(k):
                errors.append(f'{f}:{iid} missing required field "{k}"')
        # the served curriculum is verified-only
        if it.get('status') != 'verified':
            errors.append(f'{f}:{iid} status={it.get("status")!r} — only "verified" items may be served')
            counts['other'] += 1
        else:
            counts['verified'] += 1
        # provenance must be real, non-empty, and specific
        srcs = it.get('sources') or []
        if not srcs:
            errors.append(f'{f}:{iid} verified but has no sources (provenance required)')
        for s in srcs:
            if not isinstance(s, str) or len(s.strip()) < 12:
                errors.append(f'{f}:{iid} source looks empty/placeholder: {s!r}')
        # duplicate ids
        if iid in ids:
            errors.append(f'duplicate id {iid}')
        ids.add(iid)
        log.append((it.get('status'), iid, it.get('jp'), it.get('kana'), it.get('en'),
                    '; '.join(srcs)))

# can_do goals must reference served ids only
for d in ix['domains']:
    for c in d.get('can_do', []):
        for x in c['needs']:
            if x not in ids:
                errors.append(f'can_do goal "{c["en"]}" references unknown/unserved id {x}')

# quarantine must stay separate and must not leak back into packs
qpath = os.path.join(DATA, 'quarantine.json')
quar = []
if os.path.exists(qpath):
    q = json.load(open(qpath, encoding='utf-8'))
    for it in q.get('items', []):
        quar.append(it)
        if it.get('id') in ids:
            errors.append(f'quarantined id {it.get("id")} also appears in a served pack')
        if not it.get('quarantine_reason'):
            errors.append(f'quarantined id {it.get("id")} has no quarantine_reason')

# write the log (verified first)
with open(os.path.join(ROOT, 'VERIFICATION_LOG.md'), 'w', encoding='utf-8') as fh:
    fh.write('# Verification log\n\n')
    fh.write('Generated by `scripts/audit.py`. The app serves **verified items only**; '
             'there is no unverified mode. Items that failed verification live in '
             '`data/quarantine.json` and are never loaded.\n\n')
    fh.write(f'**Served:** {counts["verified"]} verified items. '
             f'**Quarantined (not served):** {len(quar)}.\n\n')
    fh.write('## Served (verified)\n\n')
    for st, i, jp, kn, en, src in sorted(log, key=lambda r: r[1]):
        fh.write(f'- `{i}` {jp} ({kn}) = {en}\n  - {src}\n')
    if quar:
        fh.write('\n## Quarantined — NOT served (reason each failed verification)\n\n')
        for it in sorted(quar, key=lambda r: r.get('id', '')):
            fh.write(f'- `{it.get("id")}` {it.get("jp")} ({it.get("kana")}) = {it.get("en")}\n'
                     f'  - ⚠ {it.get("quarantine_reason")}\n')

print(f'served verified={counts["verified"]} quarantined={len(quar)} '
      f'unverified-in-packs={counts["other"]}')
if errors:
    print('\nAUDIT FAILED:')
    for e in errors:
        print('  -', e)
    sys.exit(1)
print('audit OK — served curriculum is verified-only with provenance')
