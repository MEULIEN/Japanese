#!/usr/bin/env python3
"""Lists every item and its verification state. Run from the repo root: python3 scripts/audit.py"""
import json, glob
log = []
ix = json.load(open('data/index.json', encoding='utf-8')); ids = set(); n = {'verified': 0, 'draft': 0}
for f in ix['packs']:
    p = json.load(open('data/' + f, encoding='utf-8'))
    for it in p['items']:
        st = it.get('status', p['status']); n[st] += 1
        assert it['id'] not in ids, 'duplicate id ' + it['id']; ids.add(it['id'])
        for k in ('jp', 'kana', 'en', 'tier'): assert k in it, (it['id'], k)
        log.append((st, it['id'], it['jp'], it['kana'], it['en'], '; '.join(it.get('sources', p['sources']))))
        if st == 'draft': print('DRAFT   ', it['id'], it['jp'], '-', it['en'])
for d in ix['domains']:
    for c in d.get('can_do', []):
        for x in c['needs']: assert x in ids, 'unknown id in can_do: ' + x
print(n)
with open('VERIFICATION_LOG.md', 'w', encoding='utf-8') as f:
    f.write('# Verification log\n\nGenerated by scripts/audit.py. verified = source checked (listed); draft = NOT yet checked.\n\n')
    for st, i, jp, kn, en, src in sorted(log, key=lambda r: (r[0] != 'verified', r[1])):
        f.write(f'- **{st}** `{i}` {jp} ({kn}) = {en}\n  - {src}\n')
