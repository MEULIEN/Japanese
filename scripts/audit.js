#!/usr/bin/env node
/* Curriculum audit: validates data/ and regenerates VERIFICATION_LOG.md.
   Exits non-zero if anything unverified would be served or provenance is
   missing. Usage: node scripts/audit.js */
'use strict';
const fs = require('fs'), path = require('path');
const CUR = require('../js/curriculum.js');
const D = path.join(__dirname, '..', 'data');
const J = f => JSON.parse(fs.readFileSync(path.join(D, f), 'utf8'));
const index = J('index.json');
const itemFiles = index.items.map(J);
const C = CUR.build({ index, topics: J(index.topics), itemFiles, grammar: J(index.grammar), conjugation: J(index.conjugation), recovery: J(index.recovery), milestones: J(index.milestones), synonyms: J(index.synonyms) });
const q = J('quarantine.json'); const qItems = q.items || q;
const problems = [];
const raw = itemFiles.flatMap(f => f.items);
for (const i of raw) if (i.status !== 'verified') problems.push('unverified item in a served file: ' + i.id);
for (const s of C.skipped) problems.push('rejected at load: ' + s.id + ' (' + s.why + ')');
for (const i of C.items) if (!i.sources.length) problems.push('no sources: ' + i.id);
for (const x of qItems) if (C.byId[x.id]) problems.push('quarantined item is served: ' + x.id);

const src = s => typeof s === 'string' ? s : [s.name, s.matched, s.url, s.id && !s.url ? '#' + s.id : null, s.checked && 'checked ' + s.checked].filter(Boolean).join(' · ');
const byTopic = {};
for (const i of C.items) (byTopic[i.topic] = byTopic[i.topic] || []).push(i);
const count = (arr, k) => arr.reduce((m, i) => (m[i[k]] = (m[i[k]] || 0) + 1, m), {});
let md = `# Verification log\n\nGenerated by \`node scripts/audit.js\` (curriculum ${C.version}).\n\n`;
md += `**${C.items.length} verified items served** in ${C.topics.length} topics · ${C.grammar.length} sentence patterns · ${C.recovery.length} get-unstuck prompts · ${C.milestones.length} milestones · **${qItems.length} quarantined** (never served).\n\n`;
md += `By use: ${JSON.stringify(count(C.items, 'use'))} · by tier: ${JSON.stringify(count(C.items, 'tier'))} · examples: ${C.items.reduce((t, i) => t + i.examples.length, 0)}\n\n`;
md += `Rule: an item is served only if its status is \`verified\` and its sources support its written form, reading and meaning. Dictionary sources record what JMdict actually says (matched form, senses, part of speech). Verb/adjective classes come from the dictionary part of speech.\n\n`;
for (const t of C.topics) {
  const its = byTopic[t.id] || [];
  md += `## ${t.icon || ''} ${t.name} (${its.length})\n\n| id | Japanese | reading | meaning | sources |\n|---|---|---|---|---|\n`;
  for (const i of its) md += `| ${i.id} | ${i.jp} | ${i.kana} | ${String(i.en).replace(/\|/g, '/')} | ${i.sources.map(src).join('<br>').replace(/\|/g, '/')} |\n`;
  md += '\n';
}
md += `## Sentence patterns\n\n` + C.grammar.map(p => `- **${p.frame}** — ${p.sources.map(src).join('; ')}`).join('\n') + '\n\n';
md += `## Quarantined (not served)\n\n| id | Japanese | reason |\n|---|---|---|\n` + qItems.map(x => `| ${x.id} | ${x.jp || ''} | ${String(x.quarantine_reason || '').replace(/\|/g, '/')} |`).join('\n') + '\n';
fs.writeFileSync(path.join(__dirname, '..', 'VERIFICATION_LOG.md'), md);
console.log(`served verified=${C.items.length} topics=${C.topics.length} patterns=${C.grammar.length} quarantined=${qItems.length}`);
if (problems.length) { console.log('AUDIT FAILED:\n  ' + problems.join('\n  ')); process.exit(1); }
console.log('audit OK — served curriculum is verified-only with provenance');
