#!/usr/bin/env node
/* Regenerates data/index.json from the files present in data/items/.
   Adding a topic = drop a verified items file there and run this. */
'use strict';
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'data');
const items = fs.readdirSync(path.join(dir, 'items')).filter(f => f.endsWith('.json')).sort().map(f => 'items/' + f);
const d = new Date().toISOString().slice(0, 10).replace(/-/g, '.');
const idx = { schema: 2, curriculum_version: d, topics: 'topics.json', items, grammar: 'grammar.json', conjugation: 'conjugation.json', recovery: 'recovery.json', milestones: 'milestones.json',
  note: 'Generated by scripts/build_index.js. Only items with status "verified" and real sources are served; see data/SCHEMA.md.' };
fs.writeFileSync(path.join(dir, 'index.json'), JSON.stringify(idx, null, 1) + '\n');
console.log('index.json:', items.length, 'item files, version', d);
